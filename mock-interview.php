<p class="eyebrow">01 · Interview Questions</p>
<h2>Prepared Answers</h2>
<p class="sub">Key responses designed for IT job interviews based on academic guidelines and personal project experience.</p>

<div class="cards">
<article class="card">
<h3>1. Tell me about yourself.</h3>
<p>I am a recent Bachelor of Science in Information Technology graduate from Datamex College of Saint Adeline. During my studies, I gained hands-on experience building web applications, designing database schemas, and collaborating on our capstone project, Smart Assistive Vision. I enjoy solving real-world problems with code, keeping up with clean practices, and adapting to new development tools quickly.</p>
</article>

<article class="card">
<h3>2. Why did you choose BSIT?</h3>
<p>I chose BS Information Technology because I have always been passionate about technology and fascinated by how software powers modern tools and businesses. BSIT provided me with the ideal blend of software engineering, database administration, and networking fundamentals—giving me a strong base to grow as a full-stack web developer.</p>
</article>

<article class="card">
<h3>3. What is your biggest technical strength?</h3>
<p>My biggest strength is my practical approach to web development and problem-solving. Whether structuring PHP backend queries using PDO prepared statements or styling responsive UI components with HTML and CSS, I ensure my work is reliable, well-documented, and user-friendly.</p>
</article>

<article class="card">
<h3>4. How do you handle technical challenges or bugs under pressure?</h3>
<p>I approach debugging systematically: reproducing the error, reading server/browser logs, isolating variables, testing hypotheses step-by-step, and consulting documentation. During my capstone project, this structured troubleshooting helped our team solve key hardware-software integration bugs efficiently.</p>
</article>
</div>
